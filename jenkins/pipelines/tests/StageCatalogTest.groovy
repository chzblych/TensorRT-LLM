import groovy.json.JsonOutput
import groovy.json.JsonSlurper
import java.security.MessageDigest

// From the repository root: groovy jenkins/pipelines/tests/StageCatalogTest.groovy .
def root = new File(args ? args[0] : '.')
def loader = new GroovyClassLoader(this.class.classLoader)
loader.addClasspath(new File(root, 'jenkins/pipeline-library/src').absolutePath)
def catalog = loader.loadClass('trtllm.ci.stages.StageCatalog')
def raw = new JsonSlurper().parse(new File(root, 'jenkins/pipelines/test/stages.json'))
def expanded = catalog.expandForPipeline(raw)
assert expanded.values().sum { it.size() } == 156
// Pins original runtime stage names, tuple values, and group/declaration order,
// including the 33 stages generated by the old multi-node helper.
def pairs = expanded.collect { group, rows -> [group, rows.collect { name, values -> [name, values] }] }
def digest = MessageDigest.getInstance('SHA-256').digest(JsonOutput.toJson(pairs).getBytes('UTF-8')).encodeHex().toString()
assert digest == '803d69215cb57c5a89e6e8ced5cf289c9b9367d03082352bf5808cd87f795d1b'

def definition = { List rows, String runner ->
    [version: 1, groups: [[name: 'example', arch: 'x86', runner: runner, stages: rows]]]
}
def stage = [name: 'A10-PyTorch-{shard}', platform: 'a10', testList: 'l0_a10', splits: 3]
def rows = catalog.expand(definition([stage, stage + [name: 'Unsharded', splits: 1]], 'kubernetes')).example
assert rows.keySet().toList() == ['A10-PyTorch-1', 'A10-PyTorch-2', 'A10-PyTorch-3', 'Unsharded']
assert rows['A10-PyTorch-2'] == ['a10', 'l0_a10', 2, 3]
assert rows.Unsharded == ['a10', 'l0_a10', 1, 1]
rows['A10-PyTorch-1'][0] = 'mutated'
assert catalog.expand(definition([stage], 'kubernetes')).example['A10-PyTorch-1'][0] == 'a10'
assert rows['A10-PyTorch-2'][0] == 'a10'

def modelExpress = stage + [splits: 1, gpuCount: 2, options: [modelExpress: true]]
assert catalog.expand(definition([modelExpress], 'kubernetes')).example.values().first() == ['a10', 'l0_a10', 1, 1, 2, true]
def slurm = stage + [splits: 1, gpuCount: 4, nodeCount: 1, options: [useClusterDurations: true]]
assert catalog.expand(definition([slurm], 'slurmAgent')).example.values().first() ==
    ['a10', 'l0_a10', 1, 1, 4, 1, false, true]
assert catalog.expand(definition([stage + [splits: 1]], 'sbatch')).example.values().first() ==
    ['a10', 'l0_a10', 1, 1, 1, 1, true]
def multiNode = stage + [splits: 1, gpuCount: 8, nodeCount: 2, options: [runWithSbatch: false]]
assert catalog.expand(definition([multiNode], 'sbatch')).example.values().first() ==
    ['a10', 'l0_a10', 1, 1, 8, 2, false]

def invalid = [
    definition([stage + [splits: 0]], 'kubernetes'), definition([stage + [splits: -1]], 'kubernetes'),
    definition([stage + [splits: 1.5]], 'kubernetes'), definition([stage + [splits: true]], 'kubernetes'),
    definition([stage + [name: 'MissingShard']], 'kubernetes'), definition([stage, stage], 'kubernetes'),
    definition([stage + [gpuCount: 0]], 'kubernetes'), definition([stage + [options: [typo: true]]], 'kubernetes'),
    definition([stage + [options: [modelExpress: 'true']]], 'kubernetes'),
    definition([stage + [options: [runWithSbatch: true]]], 'kubernetes'),
    definition([stage + [nodeCount: 2]], 'slurmAgent'),
    definition([stage + [options: null]], 'kubernetes'), definition([stage + [options: false]], 'kubernetes'),
    definition([stage + [options: []]], 'kubernetes'), definition([stage + [runner: null]], 'kubernetes'),
    definition([stage + [runner: '']], 'kubernetes'),
    [version: true, groups: []], [version: 1.0, groups: []],
]
invalid.each { value ->
    try {
        catalog.expand(value)
        assert false: 'invalid catalog should fail before execution'
    } catch (IllegalArgumentException expected) {}
}
def pipelineDefinition = { String groupName, Map row ->
    def value = new JsonSlurper().parseText(JsonOutput.toJson(raw))
    value.groups.each { group -> group.stages = group.name == groupName ? [row] : [] }
    return value
}
def unknownGroup = pipelineDefinition('x86TestConfigs', stage)
unknownGroup.groups[0].name = 'unknown'
def missingGroup = pipelineDefinition('x86TestConfigs', stage)
missingGroup.groups.remove(missingGroup.groups.size() - 1)
def wrongArch = pipelineDefinition('x86TestConfigs', stage)
wrongArch.groups[0].arch = 'sbsa'
def wrongDefault = pipelineDefinition('x86TestConfigs', stage)
wrongDefault.groups[0].runner = 'sbatch'
wrongDefault.groups[0].stages = []
def wrongRunner = pipelineDefinition('x86TestConfigs', stage + [runner: 'sbatch'])
def sbsaModelExpress = pipelineDefinition('SBSATestConfigs', modelExpress)
[unknownGroup, missingGroup, wrongArch, wrongDefault, wrongRunner, sbsaModelExpress].each { value ->
    try {
        catalog.expandForPipeline(value)
        assert false: 'unimplemented Pipeline routing must fail before dispatch'
    } catch (IllegalArgumentException expected) {}
}
def sbsaGpu = catalog.expandForPipeline(pipelineDefinition('SBSATestConfigs', stage + [gpuCount: 2]))
assert sbsaGpu.SBSATestConfigs['A10-PyTorch-2'] == ['a10', 'l0_a10', 2, 3, 2]
println 'Stage catalog checks passed: 156 original tuples/order, shard expansion, runner options, and invalid definitions.'

// The entry retains this stateless helper across Pipeline checkpoints.
def serializedCatalog = new ByteArrayOutputStream()
new ObjectOutputStream(serializedCatalog).writeObject(loader.loadClass('trtllm.ci.stages.StageCatalog').newInstance())
assert serializedCatalog.size() > 0
